package com.hautetech.ndadiee.model;

/**
 * Définit les types de contenus disponibles dans l'application Ndadiee.
 *
 * Cette énumération permet d'identifier la catégorie d'un contenu
 * afin de faciliter son traitement dans les fonctionnalités telles
 * que les commentaires, les votes et les interactions entre utilisateurs.
 */
public enum ContentType {
    QUESTION,
    ANSWER,
    ARTICLE,
    PROJECT
}
