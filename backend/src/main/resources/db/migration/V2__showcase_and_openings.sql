-- =============================================================================
-- Vitrine des projets et rôles recherchés (design 3A et 3D)
-- =============================================================================

-- ─── Vitrine : accroche et couverture de chaque projet ───────────────────────
-- La couverture existe en deux tailles (la miniature sert aux cartes) ; une photo
-- empruntée garde son crédit et le lien vers sa source, affichés avec elle.
ALTER TABLE projects
    ADD COLUMN tagline             VARCHAR(200),
    ADD COLUMN cover_url           VARCHAR(500),
    ADD COLUMN cover_thumbnail_url VARCHAR(500),
    ADD COLUMN cover_credit        VARCHAR(200),
    ADD COLUMN cover_source_url    VARCHAR(500);

CREATE INDEX idx_projects_stars ON projects (stars_count DESC);

-- ─── Rôles recherchés par les projets (« annonces ») ─────────────────────────
-- role : catégorie du catalogue (FRONTEND, MOBILE, DESIGN...), title : intitulé
-- libre (« Dev mobile React Native »). Une issue « premier pas » sert de candidature.
CREATE TABLE project_openings (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at           TIMESTAMPTZ  NOT NULL,
    updated_at           TIMESTAMPTZ  NOT NULL,
    project_id           BIGINT       NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    role                 VARCHAR(20)  NOT NULL,
    title                VARCHAR(120) NOT NULL,
    description          VARCHAR(500),
    seats                INTEGER      NOT NULL DEFAULT 1,
    starter_issue_number INTEGER,
    starter_issue_title  VARCHAR(200),
    is_open              BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_project_openings_seats CHECK (seats BETWEEN 1 AND 20)
);

CREATE INDEX idx_project_openings_project ON project_openings (project_id);
CREATE INDEX idx_project_openings_open_role ON project_openings (is_open, role);
