-- =============================================================================
-- Inventaire des fichiers envoyés par les membres (images du forum et des projets)
-- =============================================================================
--
-- Comme V3 à V7, le script tient dans un bloc DO. Avec `ddl-auto: create-drop` (réglage de développement),
-- Hibernate recrée le schéma depuis les entités après Flyway : il n'y a alors aucune table à modifier. Avec
-- `validate` (le réglage prévu, et celui de la production), la migration s'applique entièrement.

DO $$
BEGIN
    IF to_regclass('projects') IS NULL THEN
        RAISE NOTICE 'V8 : tables absentes (schéma créé par Hibernate), rien à migrer';
        RETURN;
    END IF;

    -- Un fichier par ligne, sous sa clé dans le stockage (R2, ou le disque en développement). purpose : FORUM ou
    -- PROJECT. Une image de projet est rattachée au projet qui la montre ; sans projet depuis le délai de garde
    -- (updated_at), elle est supprimée. Le compte ou le projet supprimé, la ligne reste, sans lui.
    CREATE TABLE media_uploads (
        id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        created_at   TIMESTAMPTZ  NOT NULL,
        updated_at   TIMESTAMPTZ  NOT NULL,
        owner_id     BIGINT       REFERENCES users (id) ON DELETE SET NULL,
        purpose      VARCHAR(20)  NOT NULL,
        storage_key  VARCHAR(300) NOT NULL,
        url          VARCHAR(500) NOT NULL,
        content_type VARCHAR(50)  NOT NULL,
        size         BIGINT       NOT NULL,
        project_id   BIGINT       REFERENCES projects (id) ON DELETE SET NULL,
        CONSTRAINT uk_media_uploads_storage_key UNIQUE (storage_key)
    );

    CREATE INDEX idx_media_uploads_url ON media_uploads (url);
    CREATE INDEX idx_media_uploads_owner ON media_uploads (owner_id);
    CREATE INDEX idx_media_uploads_project ON media_uploads (project_id);
    -- Le ménage : les images de projet sans projet, les plus anciennes d'abord
    CREATE INDEX idx_media_uploads_orphans ON media_uploads (updated_at) WHERE project_id IS NULL AND purpose = 'PROJECT';
END
$$;
