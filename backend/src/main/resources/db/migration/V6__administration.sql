-- =============================================================================
-- Administration : suspension des comptes, contenus masqués, journal des actions
-- =============================================================================
--
-- Comme V3 à V5, le script tient dans un bloc DO. Avec `ddl-auto: create-drop` (réglage de développement),
-- Hibernate recrée le schéma depuis les entités après Flyway : il n'y a alors aucune table à modifier. Avec
-- `validate` (le réglage prévu, et celui de la production), la migration s'applique entièrement.

DO $$
BEGIN
    IF to_regclass('users') IS NULL THEN
        RAISE NOTICE 'V6 : tables absentes (schéma créé par Hibernate), rien à migrer';
        RETURN;
    END IF;

    -- ─── Comptes : suspension par l'administration, dernière connexion ──────────
    -- blocked_at : null tant que le compte est actif ; blocked_reason : montré au titulaire à la connexion
    ALTER TABLE users
        ADD COLUMN blocked_at     TIMESTAMPTZ,
        ADD COLUMN blocked_reason VARCHAR(500),
        ADD COLUMN last_login_at  TIMESTAMPTZ;

    CREATE INDEX idx_users_blocked ON users (blocked_at) WHERE blocked_at IS NOT NULL;

    -- ─── Contenus masqués : retirés des pages publiques, sans être supprimés ─────
    ALTER TABLE questions
        ADD COLUMN hidden_at     TIMESTAMPTZ,
        ADD COLUMN hidden_reason VARCHAR(500);
    ALTER TABLE answers
        ADD COLUMN hidden_at     TIMESTAMPTZ,
        ADD COLUMN hidden_reason VARCHAR(500);
    ALTER TABLE projects
        ADD COLUMN hidden_at     TIMESTAMPTZ,
        ADD COLUMN hidden_reason VARCHAR(500);

    -- Peu de contenus masqués : des index partiels, pour la vue « Masqués » du back-office
    CREATE INDEX idx_questions_hidden ON questions (hidden_at) WHERE hidden_at IS NOT NULL;
    CREATE INDEX idx_answers_hidden ON answers (hidden_at) WHERE hidden_at IS NOT NULL;
    CREATE INDEX idx_projects_hidden ON projects (hidden_at) WHERE hidden_at IS NOT NULL;

    -- ─── Journal de l'administration : qui a fait quoi, sur quoi, et pourquoi ────
    -- La cible n'a pas de clé étrangère (compte ou contenu, peut-être supprimé depuis) : son libellé est
    -- gardé tel qu'il était au moment de l'action.
    CREATE TABLE admin_actions (
        id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        created_at   TIMESTAMPTZ  NOT NULL,
        updated_at   TIMESTAMPTZ  NOT NULL,
        admin_id     BIGINT REFERENCES users (id) ON DELETE SET NULL,
        action       VARCHAR(30)  NOT NULL,
        target_type  VARCHAR(20)  NOT NULL,
        target_id    BIGINT       NOT NULL,
        target_label VARCHAR(255) NOT NULL,
        reason       VARCHAR(500),
        detail       VARCHAR(255)
    );

    CREATE INDEX idx_admin_actions_created_at ON admin_actions (created_at DESC);
    CREATE INDEX idx_admin_actions_target ON admin_actions (target_type, target_id);
END
$$;
