-- =============================================================================
-- Page projet (design 3D) : galerie, devlog, demandes de retours, activité GitHub,
-- licence du projet, candidatures liées à un rôle
-- =============================================================================
--
-- Le script tient dans un bloc DO. Avec `ddl-auto: create-drop` (réglage de développement), Hibernate
-- supprime les tables à l'arrêt et les recrée depuis les entités au démarrage suivant, après Flyway :
-- quand cette migration passe, il n'y a alors aucune table à modifier, et Hibernate crée le schéma
-- complet. Avec `validate` (le réglage prévu, et celui de la production), les tables sont là et la
-- migration s'applique entièrement.

DO $$
BEGIN
    IF to_regclass('projects') IS NULL THEN
        RAISE NOTICE 'V3 : tables absentes (schéma créé par Hibernate), rien à migrer';
        RETURN;
    END IF;

    -- ─── Projet : licence du code ─────────────────────────────────────────────────
    -- license : identifiant SPDX (« MIT », « Apache-2.0 »)
    ALTER TABLE projects
        ADD COLUMN license VARCHAR(40);

    -- ─── Membres : rôle tenu dans l'équipe, annonce à laquelle on a répondu ──────
    -- specialty : un rôle du catalogue (MOBILE, DATA...) ; motivation : le mot de la candidature
    ALTER TABLE project_members
        ADD COLUMN specialty  VARCHAR(20),
        ADD COLUMN opening_id BIGINT REFERENCES project_openings (id) ON DELETE SET NULL,
        ADD COLUMN motivation VARCHAR(500);

    CREATE INDEX idx_project_members_opening ON project_members (opening_id, status);

    -- ─── Galerie : captures et photos, après la couverture ───────────────────────
    CREATE TABLE project_media (
        id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        created_at    TIMESTAMPTZ  NOT NULL,
        updated_at    TIMESTAMPTZ  NOT NULL,
        project_id    BIGINT       NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
        position      INTEGER      NOT NULL,
        kind          VARCHAR(20)  NOT NULL,
        url           VARCHAR(500) NOT NULL,
        thumbnail_url VARCHAR(500),
        caption       VARCHAR(200),
        credit        VARCHAR(200),
        source_url    VARCHAR(500),
        width         INTEGER,
        height        INTEGER
    );

    CREATE INDEX idx_project_media_project ON project_media (project_id, position);

    -- ─── Devlog : ce qui vient de changer, version par version ───────────────────
    CREATE TABLE devlog_entries (
        id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        created_at TIMESTAMPTZ   NOT NULL,
        updated_at TIMESTAMPTZ   NOT NULL,
        project_id BIGINT        NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
        author_id  BIGINT        NOT NULL REFERENCES users (id),
        version    VARCHAR(30),
        body       VARCHAR(1000) NOT NULL
    );

    CREATE INDEX idx_devlog_entries_project ON devlog_entries (project_id, created_at DESC);

    -- ─── Demandes de retours, et les retours de la communauté ───────────────────
    -- Un retour par membre et par demande ; rating : de 1 à 5, facultative
    CREATE TABLE feedback_calls (
        id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        created_at TIMESTAMPTZ  NOT NULL,
        updated_at TIMESTAMPTZ  NOT NULL,
        project_id BIGINT       NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
        author_id  BIGINT       NOT NULL REFERENCES users (id),
        title      VARCHAR(140) NOT NULL,
        prompt     VARCHAR(500),
        is_open    BOOLEAN      NOT NULL DEFAULT TRUE
    );

    CREATE INDEX idx_feedback_calls_project ON feedback_calls (project_id, is_open);

    CREATE TABLE feedback (
        id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        created_at TIMESTAMPTZ   NOT NULL,
        updated_at TIMESTAMPTZ   NOT NULL,
        call_id    BIGINT        NOT NULL REFERENCES feedback_calls (id) ON DELETE CASCADE,
        author_id  BIGINT        NOT NULL REFERENCES users (id),
        rating     INTEGER,
        body       VARCHAR(1000) NOT NULL,
        CONSTRAINT uk_feedback_call_author UNIQUE (call_id, author_id),
        CONSTRAINT ck_feedback_rating CHECK (rating BETWEEN 1 AND 5)
    );

    -- ─── Activité GitHub : un relevé par projet, remplacé à chaque synchronisation ──
    -- commit_weeks : commits des 12 dernières semaines, de la plus ancienne à la semaine en cours
    CREATE TABLE project_github_activity (
        id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        created_at        TIMESTAMPTZ NOT NULL,
        updated_at        TIMESTAMPTZ NOT NULL,
        project_id        BIGINT      NOT NULL UNIQUE REFERENCES projects (id) ON DELETE CASCADE,
        stars             INTEGER     NOT NULL,
        forks             INTEGER     NOT NULL,
        open_issues       INTEGER     NOT NULL,
        good_first_issues INTEGER     NOT NULL,
        contributors      INTEGER     NOT NULL,
        commit_weeks      INTEGER[]   NOT NULL,
        last_release      VARCHAR(40),
        last_release_at   TIMESTAMPTZ,
        last_commit_at    TIMESTAMPTZ,
        synced_at         TIMESTAMPTZ NOT NULL
    );
END
$$;
