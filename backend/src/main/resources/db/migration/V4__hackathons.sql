-- =============================================================================
-- Hackathons : l'événement, son programme, ses prix, et les équipes inscrites
-- (des projets de la vitrine)
-- =============================================================================
--
-- Comme V3, le script tient dans un bloc DO. Avec `ddl-auto: create-drop` (réglage de développement),
-- Hibernate supprime les tables à l'arrêt et les recrée depuis les entités au démarrage suivant, après
-- Flyway : quand cette migration passe, il n'y a alors aucune table à modifier, et Hibernate crée le
-- schéma complet. Avec `validate` (le réglage prévu, et celui de la production), les tables sont là et
-- la migration s'applique entièrement.

DO $$
BEGIN
    IF to_regclass('projects') IS NULL THEN
        RAISE NOTICE 'V4 : tables absentes (schéma créé par Hibernate), rien à migrer';
        RETURN;
    END IF;

    -- ─── Le hackathon ────────────────────────────────────────────────────────────
    -- format : REMOTE, ONSITE ou HYBRID ; timezone : fuseau IANA de l'événement (« Africa/Abidjan »),
    -- où se lisent les horaires sur place. Le statut (à venir, en cours, terminé) se déduit des dates.
    CREATE TABLE hackathons (
        id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        created_at             TIMESTAMPTZ  NOT NULL,
        updated_at             TIMESTAMPTZ  NOT NULL,
        title                  VARCHAR(120) NOT NULL,
        slug                   VARCHAR(140) NOT NULL,
        tagline                VARCHAR(200),
        description            TEXT         NOT NULL,
        organizer_name         VARCHAR(150) NOT NULL,
        format                 VARCHAR(20)  NOT NULL,
        country                VARCHAR(2),
        city                   VARCHAR(100),
        timezone               VARCHAR(40)  NOT NULL,
        starts_at              TIMESTAMPTZ  NOT NULL,
        ends_at                TIMESTAMPTZ  NOT NULL,
        registration_closes_at TIMESTAMPTZ  NOT NULL,
        prize_pool             VARCHAR(100),
        min_team_size          INTEGER      NOT NULL,
        max_team_size          INTEGER      NOT NULL,
        max_teams              INTEGER,
        created_by_id          BIGINT       NOT NULL REFERENCES users (id),
        CONSTRAINT uk_hackathons_slug UNIQUE (slug),
        CONSTRAINT ck_hackathons_dates CHECK (starts_at < ends_at AND registration_closes_at <= starts_at),
        CONSTRAINT ck_hackathons_team_size CHECK (min_team_size BETWEEN 1 AND max_team_size AND max_team_size <= 20)
    );

    CREATE INDEX idx_hackathons_starts_at ON hackathons (starts_at);
    CREATE INDEX idx_hackathons_ends_at ON hackathons (ends_at);

    CREATE TABLE hackathon_tags (
        hackathon_id BIGINT NOT NULL REFERENCES hackathons (id) ON DELETE CASCADE,
        tag_id       BIGINT NOT NULL REFERENCES tags (id) ON DELETE CASCADE,
        PRIMARY KEY (hackathon_id, tag_id)
    );

    CREATE INDEX idx_hackathon_tags_tag ON hackathon_tags (tag_id);

    -- ─── Programme : les temps forts (coup d'envoi, démos, résultats…) ───────────
    CREATE TABLE hackathon_milestones (
        hackathon_id BIGINT       NOT NULL REFERENCES hackathons (id) ON DELETE CASCADE,
        scheduled_at TIMESTAMPTZ  NOT NULL,
        label        VARCHAR(120) NOT NULL
    );

    CREATE INDEX idx_hackathon_milestones_hackathon ON hackathon_milestones (hackathon_id, scheduled_at);

    -- ─── Prix, dans l'ordre où l'organisateur les présente ───────────────────────
    CREATE TABLE hackathon_prizes (
        hackathon_id BIGINT       NOT NULL REFERENCES hackathons (id) ON DELETE CASCADE,
        position     INTEGER      NOT NULL,
        title        VARCHAR(80)  NOT NULL,
        reward       VARCHAR(150) NOT NULL,
        PRIMARY KEY (hackathon_id, position)
    );

    -- ─── Équipes : les projets inscrits ──────────────────────────────────────────
    -- L'équipe, ce sont les membres du projet ; les rôles qu'elle cherche, ses annonces ouvertes.
    -- rank : place au palmarès (une équipe par place), award : distinction (« Prix du public »).
    CREATE TABLE hackathon_teams (
        id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        created_at       TIMESTAMPTZ NOT NULL,
        updated_at       TIMESTAMPTZ NOT NULL,
        hackathon_id     BIGINT      NOT NULL REFERENCES hackathons (id) ON DELETE CASCADE,
        project_id       BIGINT      NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
        registered_by_id BIGINT      NOT NULL REFERENCES users (id),
        pitch            VARCHAR(280),
        rank             INTEGER,
        award            VARCHAR(80),
        CONSTRAINT uk_hackathon_teams_hackathon_project UNIQUE (hackathon_id, project_id),
        CONSTRAINT uk_hackathon_teams_hackathon_rank UNIQUE (hackathon_id, rank),
        CONSTRAINT ck_hackathon_teams_rank CHECK (rank BETWEEN 1 AND 10)
    );

    CREATE INDEX idx_hackathon_teams_project ON hackathon_teams (project_id);
END
$$;
