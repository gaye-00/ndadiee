-- ════════════════════════════════════════════════════════════════════
--  Utilisateurs (héritage SINGLE_TABLE : Developer et Admin)
-- ════════════════════════════════════════════════════════════════════

CREATE TABLE users (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_type          VARCHAR(31)  NOT NULL,
    created_at         TIMESTAMPTZ  NOT NULL,
    updated_at         TIMESTAMPTZ  NOT NULL,
    username           VARCHAR(30)  NOT NULL,
    email              VARCHAR(255) NOT NULL,
    password           VARCHAR(255) NOT NULL,
    full_name          VARCHAR(255) NOT NULL,
    avatar_url         VARCHAR(500),
    preferred_language VARCHAR(20)  NOT NULL,
    role               VARCHAR(20)  NOT NULL,
    -- Colonnes propres aux développeurs (vides pour les admins)
    bio                TEXT,
    country            VARCHAR(2),
    city               VARCHAR(255),
    github_url         VARCHAR(500),
    linkedin_url       VARCHAR(500),
    website_url        VARCHAR(500),
    reputation         INTEGER,
    level              VARCHAR(20),
    open_to_work       BOOLEAN,
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_type CHECK (user_type IN ('developer', 'admin')),
    CONSTRAINT ck_users_developer CHECK (
        user_type <> 'developer' OR (reputation IS NOT NULL AND open_to_work IS NOT NULL))
);

CREATE INDEX idx_users_country ON users (country);
CREATE INDEX idx_users_reputation ON users (reputation DESC);

-- ════════════════════════════════════════════════════════════════════
--  Tags (servent aussi de compétences sur les profils)
-- ════════════════════════════════════════════════════════════════════

CREATE TABLE tags (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TIMESTAMPTZ NOT NULL,
    updated_at  TIMESTAMPTZ NOT NULL,
    name        VARCHAR(50) NOT NULL,
    slug        VARCHAR(60) NOT NULL,
    description TEXT,
    usage_count INTEGER     NOT NULL DEFAULT 0,
    CONSTRAINT uk_tags_name UNIQUE (name),
    CONSTRAINT uk_tags_slug UNIQUE (slug)
);

CREATE TABLE user_skills (
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    tag_id  BIGINT NOT NULL REFERENCES tags (id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, tag_id)
);

CREATE TABLE user_followed_tags (
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    tag_id  BIGINT NOT NULL REFERENCES tags (id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, tag_id)
);

CREATE TABLE user_follows (
    follower_id  BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    following_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    PRIMARY KEY (follower_id, following_id),
    CONSTRAINT ck_user_follows_not_self CHECK (follower_id <> following_id)
);

CREATE INDEX idx_user_skills_tag ON user_skills (tag_id);
CREATE INDEX idx_user_followed_tags_tag ON user_followed_tags (tag_id);
CREATE INDEX idx_user_follows_following ON user_follows (following_id);

-- ════════════════════════════════════════════════════════════════════
--  Questions / réponses
-- ════════════════════════════════════════════════════════════════════

CREATE TABLE questions (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at         TIMESTAMPTZ  NOT NULL,
    updated_at         TIMESTAMPTZ  NOT NULL,
    title              VARCHAR(255) NOT NULL,
    slug               VARCHAR(255) NOT NULL,
    body               TEXT         NOT NULL,
    author_id          BIGINT       NOT NULL REFERENCES users (id),
    view_count         INTEGER      NOT NULL DEFAULT 0,
    score              INTEGER      NOT NULL DEFAULT 0,
    answer_count       INTEGER      NOT NULL DEFAULT 0,
    accepted_answer_id BIGINT,
    status             VARCHAR(20)  NOT NULL,
    CONSTRAINT uk_questions_slug UNIQUE (slug),
    CONSTRAINT uk_questions_accepted_answer UNIQUE (accepted_answer_id)
);

CREATE TABLE answers (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TIMESTAMPTZ NOT NULL,
    updated_at  TIMESTAMPTZ NOT NULL,
    body        TEXT        NOT NULL,
    question_id BIGINT      NOT NULL REFERENCES questions (id) ON DELETE CASCADE,
    author_id   BIGINT      NOT NULL REFERENCES users (id),
    score       INTEGER     NOT NULL DEFAULT 0,
    accepted    BOOLEAN     NOT NULL DEFAULT FALSE
);

-- Référence circulaire questions <-> answers : la clé étrangère est ajoutée après coup.
ALTER TABLE questions
    ADD CONSTRAINT fk_questions_accepted_answer
        FOREIGN KEY (accepted_answer_id) REFERENCES answers (id) ON DELETE SET NULL;

CREATE TABLE question_tags (
    question_id BIGINT NOT NULL REFERENCES questions (id) ON DELETE CASCADE,
    tag_id      BIGINT NOT NULL REFERENCES tags (id) ON DELETE CASCADE,
    PRIMARY KEY (question_id, tag_id)
);

CREATE INDEX idx_questions_author ON questions (author_id);
CREATE INDEX idx_questions_created_at ON questions (created_at DESC);
CREATE INDEX idx_answers_question ON answers (question_id);
CREATE INDEX idx_answers_author ON answers (author_id);
CREATE INDEX idx_question_tags_tag ON question_tags (tag_id);

-- ════════════════════════════════════════════════════════════════════
--  Articles
-- ════════════════════════════════════════════════════════════════════

CREATE TABLE articles (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at           TIMESTAMPTZ  NOT NULL,
    updated_at           TIMESTAMPTZ  NOT NULL,
    title                VARCHAR(255) NOT NULL,
    slug                 VARCHAR(255) NOT NULL,
    content              TEXT         NOT NULL,
    cover_image_url      VARCHAR(500),
    reading_time_minutes INTEGER      NOT NULL DEFAULT 0,
    author_id            BIGINT       NOT NULL REFERENCES users (id),
    language             VARCHAR(20)  NOT NULL,
    status               VARCHAR(20)  NOT NULL,
    published_at         TIMESTAMPTZ,
    score                INTEGER      NOT NULL DEFAULT 0,
    view_count           INTEGER      NOT NULL DEFAULT 0,
    CONSTRAINT uk_articles_slug UNIQUE (slug)
);

CREATE TABLE article_tags (
    article_id BIGINT NOT NULL REFERENCES articles (id) ON DELETE CASCADE,
    tag_id     BIGINT NOT NULL REFERENCES tags (id) ON DELETE CASCADE,
    PRIMARY KEY (article_id, tag_id)
);

CREATE INDEX idx_articles_author ON articles (author_id);
CREATE INDEX idx_articles_status_published_at ON articles (status, published_at DESC);
CREATE INDEX idx_article_tags_tag ON article_tags (tag_id);

-- ════════════════════════════════════════════════════════════════════
--  Commentaires et votes (cible polymorphe : pas de clé étrangère)
-- ════════════════════════════════════════════════════════════════════

CREATE TABLE comments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TIMESTAMPTZ NOT NULL,
    updated_at  TIMESTAMPTZ NOT NULL,
    body        TEXT        NOT NULL,
    author_id   BIGINT      NOT NULL REFERENCES users (id),
    target_type VARCHAR(20) NOT NULL,
    target_id   BIGINT      NOT NULL
);

CREATE INDEX idx_comments_target ON comments (target_type, target_id);
CREATE INDEX idx_comments_author ON comments (author_id);

CREATE TABLE votes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TIMESTAMPTZ NOT NULL,
    updated_at  TIMESTAMPTZ NOT NULL,
    user_id     BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    target_type VARCHAR(20) NOT NULL,
    target_id   BIGINT      NOT NULL,
    value       INTEGER     NOT NULL,
    -- Un seul vote par personne et par contenu
    CONSTRAINT uk_votes_user_target UNIQUE (user_id, target_type, target_id),
    CONSTRAINT ck_votes_value CHECK (value IN (-1, 1))
);

CREATE INDEX idx_votes_target ON votes (target_type, target_id);

-- ════════════════════════════════════════════════════════════════════
--  Projets open source
-- ════════════════════════════════════════════════════════════════════

CREATE TABLE projects (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at               TIMESTAMPTZ  NOT NULL,
    updated_at               TIMESTAMPTZ  NOT NULL,
    name                     VARCHAR(255) NOT NULL,
    slug                     VARCHAR(255) NOT NULL,
    description              TEXT,
    repository_url           VARCHAR(500),
    demo_url                 VARCHAR(500),
    logo_url                 VARCHAR(500),
    owner_id                 BIGINT       NOT NULL REFERENCES users (id),
    looking_for_contributors BOOLEAN      NOT NULL DEFAULT FALSE,
    stars_count              INTEGER      NOT NULL DEFAULT 0,
    CONSTRAINT uk_projects_slug UNIQUE (slug)
);

CREATE TABLE project_members (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    project_id BIGINT      NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    role       VARCHAR(20) NOT NULL,
    status     VARCHAR(20) NOT NULL,
    CONSTRAINT uk_project_members_project_user UNIQUE (project_id, user_id)
);

CREATE TABLE project_tags (
    project_id BIGINT NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    tag_id     BIGINT NOT NULL REFERENCES tags (id) ON DELETE CASCADE,
    PRIMARY KEY (project_id, tag_id)
);

CREATE INDEX idx_projects_owner ON projects (owner_id);
CREATE INDEX idx_projects_created_at ON projects (created_at DESC);
CREATE INDEX idx_project_members_user ON project_members (user_id);
CREATE INDEX idx_project_tags_tag ON project_tags (tag_id);

-- ════════════════════════════════════════════════════════════════════
--  Opportunités
-- ════════════════════════════════════════════════════════════════════

CREATE TABLE opportunities (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at       TIMESTAMPTZ  NOT NULL,
    updated_at       TIMESTAMPTZ  NOT NULL,
    title            VARCHAR(255) NOT NULL,
    description      TEXT         NOT NULL,
    company_name     VARCHAR(255) NOT NULL,
    company_logo_url VARCHAR(500),
    type             VARCHAR(20)  NOT NULL,
    work_mode        VARCHAR(20)  NOT NULL,
    country          VARCHAR(2),
    city             VARCHAR(255),
    salary_range     VARCHAR(255),
    apply_url        VARCHAR(500),
    deadline         DATE,
    posted_by_id     BIGINT       NOT NULL REFERENCES users (id),
    active           BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE opportunity_tags (
    opportunity_id BIGINT NOT NULL REFERENCES opportunities (id) ON DELETE CASCADE,
    tag_id         BIGINT NOT NULL REFERENCES tags (id) ON DELETE CASCADE,
    PRIMARY KEY (opportunity_id, tag_id)
);

CREATE INDEX idx_opportunities_posted_by ON opportunities (posted_by_id);
CREATE INDEX idx_opportunities_active_created_at ON opportunities (active, created_at DESC);
CREATE INDEX idx_opportunity_tags_tag ON opportunity_tags (tag_id);

