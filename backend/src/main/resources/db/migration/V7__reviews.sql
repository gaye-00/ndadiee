-- =============================================================================
-- Revues de code : les pull requests des projets, leurs relecteurs et les commentaires de revue
-- (design 3B « Revues qui t'attendent », 3C « Revue de code communautaire »)
-- =============================================================================
--
-- Comme V3 à V6, le script tient dans un bloc DO : avec `ddl-auto: create-drop` (réglage de développement),
-- Hibernate crée le schéma complet après Flyway, sur une base sans tables. Avec `validate` (le réglage prévu, et
-- celui de la production), les tables sont là et la migration s'applique entièrement.

DO $$
BEGIN
    IF to_regclass('projects') IS NULL THEN
        RAISE NOTICE 'V7 : tables absentes (schéma créé par Hibernate), rien à migrer';
        RETURN;
    END IF;

    -- ─── La pull request ─────────────────────────────────────────────────────────
    -- status : OPEN, MERGED ou CLOSED ; community : ouverte aux relecteurs hors de l'équipe ;
    -- checks_* : vérifications réussies et en échec, les autres tournent encore
    CREATE TABLE pull_requests (
        id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        created_at           TIMESTAMPTZ    NOT NULL,
        updated_at           TIMESTAMPTZ    NOT NULL,
        project_id           BIGINT         NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
        number               INTEGER        NOT NULL,
        title                VARCHAR(200)   NOT NULL,
        body                 TEXT,
        author_id            BIGINT         NOT NULL REFERENCES users (id),
        status               VARCHAR(20)    NOT NULL,
        draft                BOOLEAN        NOT NULL DEFAULT FALSE,
        community            BOOLEAN        NOT NULL DEFAULT FALSE,
        source_branch        VARCHAR(120)   NOT NULL,
        target_branch        VARCHAR(120)   NOT NULL,
        commits              INTEGER        NOT NULL,
        files_changed        INTEGER        NOT NULL,
        additions            INTEGER        NOT NULL,
        deletions            INTEGER        NOT NULL,
        checks_total         INTEGER        NOT NULL,
        checks_passed        INTEGER        NOT NULL,
        checks_failed        INTEGER        NOT NULL,
        starter_issue_number INTEGER,
        labels               VARCHAR(255)[] NOT NULL,
        merged_at            TIMESTAMPTZ,
        closed_at            TIMESTAMPTZ,
        last_activity_at     TIMESTAMPTZ    NOT NULL,
        CONSTRAINT uk_pull_requests_project_number UNIQUE (project_id, number),
        CONSTRAINT ck_pull_requests_status CHECK (status IN ('OPEN', 'MERGED', 'CLOSED')),
        CONSTRAINT ck_pull_requests_checks CHECK (checks_passed + checks_failed <= checks_total)
    );

    CREATE INDEX idx_pull_requests_author ON pull_requests (author_id);
    CREATE INDEX idx_pull_requests_open ON pull_requests (status, last_activity_at DESC);

    -- ─── Les relecteurs ─────────────────────────────────────────────────────────
    -- state : REQUESTED, COMMENTED, APPROVED ou CHANGES_REQUESTED ; required : l'équipe attend sa revue ;
    -- community : hors de l'équipe du projet
    CREATE TABLE pull_request_reviewers (
        id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        created_at      TIMESTAMPTZ NOT NULL,
        updated_at      TIMESTAMPTZ NOT NULL,
        pull_request_id BIGINT      NOT NULL REFERENCES pull_requests (id) ON DELETE CASCADE,
        reviewer_id     BIGINT      NOT NULL REFERENCES users (id),
        state           VARCHAR(20) NOT NULL,
        required        BOOLEAN     NOT NULL DEFAULT FALSE,
        community       BOOLEAN     NOT NULL DEFAULT FALSE,
        submitted_at    TIMESTAMPTZ,
        CONSTRAINT uk_pull_request_reviewers_pr_reviewer UNIQUE (pull_request_id, reviewer_id),
        CONSTRAINT ck_pull_request_reviewers_state CHECK (state IN ('REQUESTED', 'COMMENTED', 'APPROVED', 'CHANGES_REQUESTED'))
    );

    CREATE INDEX idx_pull_request_reviewers_reviewer ON pull_request_reviewers (reviewer_id, state);

    -- ─── Les commentaires de revue : sur la conversation, ou sur une ligne du diff ─
    CREATE TABLE review_comments (
        id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        created_at      TIMESTAMPTZ  NOT NULL,
        updated_at      TIMESTAMPTZ  NOT NULL,
        pull_request_id BIGINT       NOT NULL REFERENCES pull_requests (id) ON DELETE CASCADE,
        author_id       BIGINT       NOT NULL REFERENCES users (id),
        body            TEXT         NOT NULL,
        path            VARCHAR(300),
        line            INTEGER,
        suggestion      TEXT
    );

    CREATE INDEX idx_review_comments_pull_request ON review_comments (pull_request_id, created_at);
END
$$;
