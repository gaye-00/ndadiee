-- =============================================================================
-- Pull requests synchronisées depuis le dépôt GitHub d'un projet : l'adresse de la PR, son dernier commit, son
-- auteur sur GitHub (qui n'est pas forcément inscrit sur Ndadiee), et l'état de la synchronisation de chaque projet
-- =============================================================================
--
-- Comme V3 à V8, le script tient dans un bloc DO : avec `ddl-auto: create-drop` (réglage de développement),
-- Hibernate crée le schéma complet après Flyway, sur une base sans tables. Avec `validate` (le réglage prévu, et
-- celui de la production), les tables sont là et la migration s'applique entièrement.

DO $$
BEGIN
    IF to_regclass('pull_requests') IS NULL THEN
        RAISE NOTICE 'V9 : tables absentes (schéma créé par Hibernate), rien à migrer';
        RETURN;
    END IF;

    -- ─── La pull request : son auteur peut n'être qu'un compte GitHub ────────────
    ALTER TABLE pull_requests ALTER COLUMN author_id DROP NOT NULL;
    ALTER TABLE pull_requests
        ADD COLUMN github_url         VARCHAR(500),
        ADD COLUMN head_sha           VARCHAR(40),
        ADD COLUMN author_login       VARCHAR(39),
        ADD COLUMN author_avatar_url  VARCHAR(500),
        ADD COLUMN author_association VARCHAR(30);

    -- ─── La synchronisation de chaque projet avec son dépôt ─────────────────────
    -- error : code de la dernière tentative en échec (GITHUB_REPOSITORY_NOT_FOUND, GITHUB_RATE_LIMITED…)
    CREATE TABLE repository_syncs (
        id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        created_at    TIMESTAMPTZ  NOT NULL,
        updated_at    TIMESTAMPTZ  NOT NULL,
        project_id    BIGINT       NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
        repository_id VARCHAR(100),
        full_name     VARCHAR(140),
        attempted_at  TIMESTAMPTZ,
        synced_at     TIMESTAMPTZ,
        error         VARCHAR(40),
        CONSTRAINT uk_repository_syncs_project UNIQUE (project_id)
    );
END
$$;
