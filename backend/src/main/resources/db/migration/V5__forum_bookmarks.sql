-- =============================================================================
-- Forum : la liste de lecture (sujets enregistrés par un membre pour y revenir)
-- =============================================================================
--
-- Comme V3 et V4, le script tient dans un bloc DO. Avec `ddl-auto: create-drop` (réglage de développement),
-- Hibernate recrée le schéma depuis les entités après Flyway : il n'y a alors aucune table à modifier. Avec
-- `validate` (le réglage prévu, et celui de la production), la migration s'applique entièrement.

DO $$
BEGIN
    IF to_regclass('questions') IS NULL THEN
        RAISE NOTICE 'V5 : tables absentes (schéma créé par Hibernate), rien à migrer';
        RETURN;
    END IF;

    -- Un sujet enregistré une seule fois par membre ; la date d'enregistrement ordonne la liste de lecture.
    -- Le sujet ou le membre supprimé, l'enregistrement part avec lui.
    CREATE TABLE bookmarks (
        id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        created_at  TIMESTAMPTZ NOT NULL,
        updated_at  TIMESTAMPTZ NOT NULL,
        user_id     BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
        question_id BIGINT      NOT NULL REFERENCES questions (id) ON DELETE CASCADE,
        CONSTRAINT uk_bookmarks_user_question UNIQUE (user_id, question_id)
    );

    CREATE INDEX idx_bookmarks_question ON bookmarks (question_id);

    -- Les filtres du forum : « résolus » (réponse acceptée) et « sans réponse »
    CREATE INDEX idx_questions_accepted_answer ON questions (accepted_answer_id) WHERE accepted_answer_id IS NOT NULL;
    CREATE INDEX idx_questions_unanswered ON questions (created_at DESC) WHERE answer_count = 0;
END
$$;
